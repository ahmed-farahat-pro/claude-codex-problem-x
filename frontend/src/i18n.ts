export function makeT(lang: Lang): Translate {
  return (key, vars) => {
    let text = tables[lang][key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

/** Look up a dynamic key such as state_thinking; falls back to the raw value. */
export function tDynamic(t: Translate, prefix: string, value: string | null | undefined): string {
  if (!value) return "";
  const key = `${prefix}${value}` as StringKey;
  return key in ar ? t(key) : value;
}

export function pick(text: Bilingual | undefined, lang: Lang): string {
  if (!text) return "";
  return text[lang] || text.ar;
}

type I18n = { lang: Lang; t: Translate };

export const I18nContext = createContext<I18n>({ lang: "ar", t: makeT("ar") });

export function useI18n(): I18n {
  return useContext(I18nContext);
}
